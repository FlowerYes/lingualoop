type SeedEntry = readonly [lemma: string, translation: string, explanation?: string, example?: string];
type PhraseSense = readonly [match: RegExp, translations: Record<string, string>, meaning: string, explanation: string, example: string];

export const vocabulary = seed as unknown as Record<string, SeedEntry>;

export function normalizeWord(word: string): string {
  return word.normalize('NFC').toLocaleLowerCase('es').replace(/[^\p{L}\p{N}]/gu, '');
}

