/** Offline definitions for every token in the authored demo transcripts. */
export function lookupVocabulary(word: string, sentence = ''): WordExplanation | null {
  const key = normalizeWord(word);
  const actualCaption = sentence ? videos.flatMap((video) => video.sourcePlatform === 'tiktok' ? video.transcript : []).find((caption) => caption.text === sentence) : undefined;
  const actualWord = actualCaption && actualCaption.words.find((token) => normalizeWord(token.surface) === key);
  if (actualCaption && actualWord?.translation) {
    const lemma = actualWord.lemma || key;
    return {
      lemma,
      translation: actualWord.translation,
      contextMeaning: actualCaption.translation,
      explanation: actualWord.explanation || `“${word.replace(/[¿?¡!.,;:]/g, '')}” means “${actualWord.translation}” in this sentence.`,
      example: actualCaption.text,
    };
  }
  if (!Object.hasOwn(vocabulary, key)) return null;
  const [lemma, baseTranslation, baseExplanation, baseExample] = vocabulary[key];
  const context = sentence.normalize('NFC').toLocaleLowerCase('es').replace(/\s+/g, ' ');
  const phrase = context && phraseSenses.find(([match, translations]) => Object.hasOwn(translations, key) && match.test(context));
  if (phrase) {
    const [, translations, contextMeaning, explanation, example] = phrase;
    return { lemma, translation: translations[key], contextMeaning, explanation, example };
  }
  const sense = context ? sentenceSenses[key] : undefined;
  const translation = sense?.[0] ?? baseTranslation;
  return {
    lemma,
    translation,
    contextMeaning: `“${word.replace(/[¿?¡!.,;:]/g, '')}” means “${translation}” here.`,
    explanation: sense?.[1] ?? baseExplanation ?? (key !== lemma
      ? `This is a form of “${lemma}”. In this sentence it means “${translation}”.`
      : `Use “${lemma}” to express “${translation}”.`),
    example: sense?.[2] ?? baseExample ?? (sentence || `${word}: ${translation}.`),
  };
}
